def env_bool(name, default):
    return os.getenv(name, str(default)).strip().lower() in (
        '1', 'true', 'yes', 'on',
    )


def env_list(name):
    return [
        item.strip()
        for item in os.getenv(name, '').split(',')
        if item.strip()
    ]


